# 用户星座绑定:user_id -> 星座名(内存态,重启不持久)
_BINDINGS: dict[str, str] = {}


def _resolve_sign(arg: str) -> str | None:
    """校验并返回合法星座名,非法返回 None。"""
    return arg.strip() if arg.strip() in _SIGNS else None


def _stars(rng: random.Random) -> str:
    """按随机源生成 2-5 星评级字符串。"""
    n = rng.randint(2, 5)
    return "★" * n + "☆" * (5 - n)


def _daily_fortune(sign: str) -> str:
    """按日期+星座种子生成当日运势文案(同日同星座一致)。"""
    rng = random.Random(f"{date.today()}{sign}")
    cfg = _SIGNS[sign]
    score = rng.randint(58, 99)
    number = rng.randint(1, 99)
    color = rng.choice(cfg["colors"])
    love_star = _stars(rng)
    love = rng.choice(cfg["love"])
    career_star = _stars(rng)
    career = rng.choice(cfg["career"])
    wealth_star = _stars(rng)
    wealth = rng.choice(cfg["wealth"])
    health_star = _stars(rng)
    health = rng.choice(cfg["health"])
    short = rng.choice(cfg["short"])
    return (
        f"🔮 {sign} 今日运势\n"
        f"📅 {date.today()}\n"
        "━━━━━━━━━━━━━\n"
        f"综合指数: {score}/100\n"
        f"🎨 幸运色: {color}　🔢 幸运数字: {number}\n"
        f"❤️ 爱情运 {love_star}\n　{love}\n"
        f"💼 事业运 {career_star}\n　{career}\n"
        f"💰 财运 {wealth_star}\n　{wealth}\n"
        f"🌿 健康运 {health_star}\n　{health}\n"
        f"📝 {short}"
    )


def setup(registry) -> None:
    @registry.command("星座")
    async def horoscope(event: AgentEvent):
        arg = (event.state.get("command_arg") or "").strip()
        if not arg:
            await event.reply("用法: /星座 <星座名>,例如 /星座 白羊座")
            return None
        sign = _resolve_sign(arg)
        if not sign:
            await event.reply(
                f"未找到星座「{escape_cq(arg)}」,发送 /星座列表 查看全部 12 星座。"
            )
            return None
        await event.reply(_daily_fortune(sign))
        return None

    @registry.command("我的星座")
    async def bind(event: AgentEvent):
        arg = (event.state.get("command_arg") or "").strip()
        if not arg:
            await event.reply("用法: /我的星座 <星座名>,例如 /我的星座 双子座")
            return None
        sign = _resolve_sign(arg)
        if not sign:
            await event.reply(
                f"未找到星座「{escape_cq(arg)}」,发送 /星座列表 查看全部 12 星座。"
            )
            return None
        _BINDINGS[event.user_id] = sign
        await event.reply(f"✅ 已为你绑定星座: {sign},发送 /今日运势 即可查看。")
        return None

    @registry.command("今日运势")
    async def today(event: AgentEvent):
        sign = _BINDINGS.get(event.user_id)
        if not sign:
            await event.reply("你还没绑定星座,先用 /我的星座 <星座名> 绑定吧。")
            return None
        await event.reply(_daily_fortune(sign))
        return None

    @registry.command("星座列表")
    async def sign_list(event: AgentEvent):
        names = "、".join(_SIGNS.keys())
        await event.reply(f"📋 十二星座:\n{names}")
        return None
