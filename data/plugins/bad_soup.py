def setup(registry) -> None:
    @registry.command("毒鸡汤")
    async def bad_soup(event: AgentEvent):
        text = escape_cq(random.choice(_BAD_SOUP))
        await event.reply(f"🍯 今日毒鸡汤\n{text}")
        return None

    @registry.command("心灵鸡汤")
    async def good_soup(event: AgentEvent):
        text = escape_cq(random.choice(_GOOD_SOUP))
        await event.reply(f"🌞 今日心灵鸡汤\n{text}")
        return None

    @registry.command("鸡汤连发")
    async def soup_multi(event: AgentEvent):
        arg = (event.state.get("command_arg") or "").strip()
        if arg:
            try:
                n = int(arg)
            except ValueError:
                await event.reply("用法: /鸡汤连发 1-5。")
                return None
        else:
            n = 1
        if not 1 <= n <= 5:
            await event.reply("数量需在 1-5 之间。")
            return None
        lines = [escape_cq(random.choice(_BAD_SOUP)) for _ in range(n)]
        await event.reply("🍯 今日毒鸡汤 x{}\n{}".format(n, "\n".join(lines)))
        return None
